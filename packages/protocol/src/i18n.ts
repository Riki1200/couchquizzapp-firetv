const TEXT: Record<Language, Record<TextKey, string>> = { en, es };

/** Text for `key` in `language`, with {placeholders} filled in from `vars`. */
export function translate(language: Language, key: TextKey, vars: Record<string, string | number> = {}): string {
  const template = (TEXT[language] ?? en)[key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
}

export function isLanguage(value: unknown): value is Language {
  return value === 'en' || value === 'es';
}
